"""Generate B1b-only uniform 5x7 glyphs, enlarged 2x in existing 16x16 cells."""
import argparse,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def generated():
    font=json.loads((ROOT/'assets/osd/target_font_5x7.json').read_text())
    if set(font)!=set('ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789:'):raise ValueError('Unexpected font alphabet')
    rows=['// Generated by scripts/build_target_font.py. Do not edit glyph bits by hand.',
        '// 16x16 cell: letters/digits 14 pixels high, 2-pixel strokes; no RAM.',
        'module target_text_font(input wire [7:0] I_char,input wire [3:0] I_row,output reg [15:0] O_row_bits);',
        '    reg [34:0] glyph;', '    wire [3:0] source_y=I_row-1\'b1;',
        '    reg [4:0] row;', '    always @* begin', '        case(I_char)']
    for char,bitmap in sorted(font.items()):
        assert len(bitmap)==7 and all(len(r)==5 and set(r)<=set('01') for r in bitmap)
        value=int(''.join(bitmap),2)
        rows.append(f"            8'h{ord(char):02x}:glyph=35'h{value:09x}; // {char}")
    rows+=['            default:glyph=35\'d0;','        endcase','        case(source_y[3:1])']
    for y in range(7):rows.append(f'            3\'d{y}:row=glyph[{34-y*5}:{30-y*5}];')
    rows+=['            default:row=5\'d0;','        endcase',
        "        O_row_bits=(I_row>=1 && I_row<=14) ? {3'b000,{2{row[4]}},{2{row[3]}},{2{row[2]}},{2{row[1]}},{2{row[0]}},3'b000} : 16'd0;",
        '    end','endmodule','']
    return '\n'.join(rows)

def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    dest=ROOT/'assets/osd/target_text_font.v';text=generated()
    if a.check:
        if dest.read_text()!=text:raise RuntimeError('Generated font differs; run build_target_font.py')
        print('PASS: uniform font source matches glyph definitions.')
    else:dest.write_text(text);print(dest)
if __name__=='__main__':main()
